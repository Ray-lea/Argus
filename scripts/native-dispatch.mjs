// Generates a local Rust adapter for the application command API.
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
const source = readFileSync("src-gpui/src/commands.rs", "utf8");
const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const arms = [];
const re = /pub fn (\w+)\s*\(/g;
let match;
while ((match = re.exec(source))) {
  const name = match[1];
  if (name === "subscribe") continue;
  let i = re.lastIndex,
    level = 1;
  for (; i < source.length && level; i++) {
    if (source[i] === "(") level++;
    if (source[i] === ")") level--;
  }
  const argumentsText = source.slice(re.lastIndex, i - 1),
    signature = source.slice(i, source.indexOf("{", i));
  const parts = [];
  let angle = 0,
    paren = 0,
    start = 0;
  for (let n = 0; n < argumentsText.length; n++) {
    const c = argumentsText[n];
    if (c === "<") angle++;
    if (c === ">") angle--;
    if (c === "(") paren++;
    if (c === ")") paren--;
    if (c === "," && !angle && !paren) {
      parts.push(argumentsText.slice(start, n));
      start = n + 1;
    }
  }
  parts.push(argumentsText.slice(start));
  const args = parts
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const at = s.indexOf(":");
      const key = s.slice(0, at).trim(),
        type = s.slice(at + 1).trim();
      if (type.includes("Host")) return "host.clone()";
      if (type.startsWith("State<")) return "host.state()";
      if (type.includes("NativeWindow"))
        return 'host.get_window("main").ok_or_else(||serde_json::json!(argus_core::tr!("app.windowUnavailable")))?';
      return `argument::<${type}>(&args,${JSON.stringify(camel(key))})?`;
    });
  const call = `crate::commands::${name}(${args.join(",")})`;
  arms.push(
    `        ${JSON.stringify(name)} => ${signature.includes("Result<") ? `${call}.map(|value|serde_json::to_value(value).expect("serializable command response")).map_err(|error|serde_json::to_value(error).unwrap_or(serde_json::Value::Null))` : signature.includes("->") ? `Ok(serde_json::to_value(${call}).expect("serializable command response"))` : `{ ${call}; Ok(Value::Null) }`},`,
  );
}
const text = `//! Local command adapter. Generated by scripts/native-dispatch.mjs.\nuse crate::native_runtime::Host;\nuse argus_core::{actions::Priority,services::{ServiceAction,StartType},rules::ProcessRule};\nuse crate::settings::{Language,Theme,UpdateChannel,UpdateRoute};\nuse serde_json::Value;\nfn argument<T:serde::de::DeserializeOwned>(args:&Value,key:&str)->Result<T,Value>{serde_json::from_value(args.get(key).cloned().unwrap_or(Value::Null)).map_err(|_|serde_json::json!(argus_core::tr!("app.invalidRequest")))}\npub fn invoke(host:&Host,name:&str,args:Value)->Result<Value,Value>{\n    match name {\n${arms.join("\n")}\n        _=>Err(serde_json::json!(argus_core::tr!("app.invalidRequest"))),\n    }\n}\n`;
const formatted = execFileSync("rustfmt", ["--edition", "2024"], { input: text, encoding: "utf8" });
if (process.argv.includes("--check")) {
  if (
    readFileSync("src-gpui/src/dispatch.rs", "utf8").replaceAll("\r\n", "\n") !==
    formatted.replaceAll("\r\n", "\n")
  )
    throw new Error("Native command adapter is stale; run node scripts/native-dispatch.mjs");
} else writeFileSync("src-gpui/src/dispatch.rs", formatted);
console.log(`Generated ${arms.length} local command handlers`);
