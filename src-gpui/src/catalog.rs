//! The desktop registers its existing catalogs with the shared translation API.
pub fn register() {
    use argus_core::i18n::{Locale, register_catalog};
    macro_rules! catalogs { ($locale:literal,$($name:literal),*) => { &[$(($name,include_str!(concat!("../../locales/",$locale,"/",$name,".json")))),*] }; }
    register_catalog(
        Locale::ZhCn,
        catalogs!(
            "zh-CN",
            "actions",
            "common",
            "connections",
            "details",
            "fileLock",
            "format",
            "history",
            "onboarding",
            "performance",
            "processes",
            "services",
            "settings",
            "shell",
            "startup",
            "tasks",
            "updates"
        ),
    );
    register_catalog(
        Locale::EnUs,
        catalogs!(
            "en-US",
            "actions",
            "common",
            "connections",
            "details",
            "fileLock",
            "format",
            "history",
            "onboarding",
            "performance",
            "processes",
            "services",
            "settings",
            "shell",
            "startup",
            "tasks",
            "updates"
        ),
    );
}
